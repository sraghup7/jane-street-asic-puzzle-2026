#!/usr/bin/env python3
"""analyse.py -- C3: what the chip is made of, decided from behaviour on two stimuli.

C3's original method (cluster the graph, read counters off its shape) was measured to be
unavailable on this design: no flop's D is another flop's Q, and the transitive cone of every one of
the 92 flops reaches 90 of the other 91, so the flop-dependency graph is a single component. The
method here is behavioural instead, and it needs *two* stimuli, for a reason that cost C3 one stalled
round: the reference waveform contains only failing attempts, so the success path is never exercised
and 21 flops never change value at all. No signature can be extracted from a flop that never moves.

The second stimulus is the winning vector (tools/target.py), clocked in on the reference's own
control timeline. With it, 87 of the 92 flops move, and the ones that move exactly twice are the
per-region counters whose region holds exactly two stars -- which is what the winning grid is.

Blocks are decided by tests that are exact rather than thresholded, in this order:

  shift stage       the trace equals the serial input delayed by a fixed number of positions, with
                    zero mismatches over every enabled position of both stimuli
  ones counter bit  the maximally-long carry chain seeded from the flop that changes only when I=1,
                    verified by reading the chain as a binary number: every transition +1
  message bit       every change falls OUTSIDE the enable windows (the message path is the only
                    logic that runs between attempts)
  two-shot bit      exactly two changes under the winning stimulus and more under a failing one.
                    C4 established what these are: the per-column counters, one per column, each
                    marking exactly that column's two stars of the winning grid.
  fast bit          changes on most enabled cycles: the position/column counting that paces the
                    rest (contains the bit verified to be `p mod 11`'s bit 0)

Whatever is left is reported as unclassified with its measured signature attached, never given a
function it has not earned. The same discipline as the rest of the project: the artifact must not
claim more than the evidence carries.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from tools.puzzle import simulate as S
from tools.puzzle import verdict as V

PUZZLE = ROOT / 'build' / 'puzzle.v'
CELLS = ROOT / 'build' / 'cells.v'
OUT_REF_TB = ROOT / 'build' / 'decompose_ref_tb.v'
OUT_WIN_TB = ROOT / 'build' / 'decompose_win_tb.v'
OUT_REPORT = ROOT / 'recon' / 'derived' / 'blocks.json'
SCRATCH = ROOT / 'recon' / 'scratch' / 'analyse'

EMITTED_REF_REL = 'build/decompose_ref_tb.v'
EMITTED_WIN_REL = 'build/decompose_win_tb.v'
FLOPS = ('sky130_fd_sc_hd__dfrtp_2', 'sky130_fd_sc_hd__dfstp_2', 'sky130_fd_sc_hd__dfxtp_2')
INST_RE = re.compile(r'^  (\S+)\s+(i\d+)\s*\((.*)\);\s*$', re.M)
WIN_FEED_OFFSET = 4
CYCLES = 312
SAMPLE_DELAY_PS = 1


def flop_table() -> list[dict]:
    out = []
    text = PUZZLE.read_text(encoding='utf-8')
    for m in INST_RE.finditer(text):
        if m.group(1) not in FLOPS:
            continue
        pins = {k: v.strip() for k, v in re.findall(r'\.(\w+)\s*\(([^)]*)\)', m.group(3))}
        out.append({'inst': m.group(2), 'master': m.group(1).replace('sky130_fd_sc_hd__', ''),
                    'q': pins['Q']})
    return sorted(out, key=lambda f: f['inst'])


def windows(flags: list[str]) -> list[list[int]]:
    runs, start = [], None
    for k, v in enumerate(flags):
        if v == '1' and start is None:
            start = k
        elif v != '1' and start is not None:
            runs.append([start, k - 1])
            start = None
    if start is not None:
        runs.append([start, len(flags) - 1])
    return runs


def emit(stimulus: str, flops: list[dict], path: Path) -> dict:
    """One harness shape for both stimuli: the interface plus every flop, named, once per cycle."""
    ref_data = S.read_reference()
    half = ref_data['clock']['half_period_ps']
    events = [(t, n, S._normalise(v, 1)) for n in ('rst_n', 'enable')
              for t, v in ref_data['ref']['changes'][n]]
    if stimulus == 'winning':
        for k, bit in enumerate(V.derived_feed()):
            events.append((10000 * (WIN_FEED_OFFSET + k), 'I', bit))
    else:
        events += [(t, 'I', S._normalise(v, 1)) for t, v in ref_data['ref']['changes']['I']]
    events.sort(key=lambda r: (r[0], r[1]))

    lines = [
        f'// build/decompose_{"win" if stimulus == "winning" else "ref"}_tb.v -- C3 harness.',
        '//',
        f'// Generated by tools/puzzle/analyse.py (plan step C3). Do not edit by hand.',
        '//',
        '// The control timeline (rst_n, enable) is the reference waveform\'s, in both variants:',
        '// the one thing that differs is the data line, so a behaviour that appears under one and',
        '// not the other is attributable to the payload.',
        f'// Regenerate with:  python -m tools.puzzle decompose',
        '`timescale 1ps/1ps',
        'module decompose_tb;',
        f'  localparam integer CYCLES = {CYCLES};',
        '  reg clk = 1\'b0;',
        '  reg rst_n = 1\'b0;',
        '  reg enable = 1\'b0;',
        '  reg I = 1\'b0;',
        '  wire [7:0] O;',
        '  wire success;',
        '  integer cyc = 0;',
        '  wire VGND;',
        '  wire VPWR;',
        '  assign VGND = 1\'b0;',
        '  assign VPWR = 1\'b1;',
        '  puzzle dut (.clk(clk), .rst_n(rst_n), .enable(enable), .I(I),',
        '              .O(O), .success(success), .VGND(VGND), .VPWR(VPWR));',
        f'  always #{half} clk = ~clk;',
        '  initial begin',
    ]
    prev, i = 0, 0
    while i < len(events):
        t = events[i][0]
        same = [e for e in events if e[0] == t]
        lines.append(f'    #{t - prev} ' + ' '.join(f'{n} = 1\'b{v};' for _, n, v in same))
        prev = t
        i += len(same)
    lines += [
        '  end',
        '  always @(posedge clk) begin',
        f'    #{SAMPLE_DELAY_PS};',
        '    $display("C %0d %b %b %b %b %b", cyc, rst_n, enable, I, O, success);',
    ]
    lines += [f'    $display("F %0d {f["inst"]} %b", cyc, dut.{f["inst"]}.Q);'
              for f in flops]
    lines += [
        '    cyc = cyc + 1;',
        '    if (cyc >= CYCLES) $finish;',
        '  end',
        'endmodule',
        '',
    ]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    return ref_data


def run(stimulus: str, flops: list[dict], ref_data: dict,
        tb: Path | None = None) -> tuple[list[dict], dict]:
    """Simulate one stimulus. `tb` is overridable so a gate can run into scratch instead of
    overwriting the committed harness -- a gate that rewrites the artifact it is checking cannot
    report a drifted artifact as a failure."""
    tb = tb or (OUT_WIN_TB if stimulus == 'winning' else OUT_REF_TB)
    vvp = SCRATCH / f'{tb.stem}.vvp'
    emit(stimulus, flops, tb)
    stdout, comp_rc, sim_rc = S.compile_and_run(tb, vvp, sources=[PUZZLE, CELLS])
    (SCRATCH / f'{tb.stem}.out').write_text(stdout, encoding='utf-8', newline='\n')
    rows, q = [], {}
    for line in stdout.splitlines():
        f = line.split()
        if not f:
            continue
        if f[0] == 'C':
            rows.append({'cycle': int(f[1]), 'rst_n': f[2], 'enable': f[3], 'I': f[4],
                         'O': f[5], 'success': f[6]})
        elif f[0] == 'F':
            q.setdefault(f[2], []).append(f[3][0])
    return rows, q


